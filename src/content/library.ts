const termLabel = (terms: LibraryTerm[], id: string) => terms.find((t) => t.id === id)?.label ?? id;

export const levelLabel = (id: string) => termLabel(libraryLevels, id);
export const categoryLabel = (id: string) => termLabel(libraryCategories, id);
export const tagLabel = (id: string) => termLabel(libraryTags, id);

export function findVideo(id: string): LibraryVideo | undefined {
  return libraryVideos.find((v) => v.id === id);
}

/** Categories that actually occur inside the given level. */
export function categoriesForLevel(level: string, videos: LibraryVideo[] = libraryVideos): LibraryTerm[] {
  if (level === "all") return libraryCategories;
  const ids = new Set(videos.filter((v) => v.levels.includes(level)).flatMap((v) => v.categories));
  return libraryCategories.filter((c) => ids.has(c.id));
}

/** Tags that actually occur inside the given level + category selection. */
export function tagsFor(level: string, category: string, videos: LibraryVideo[] = libraryVideos): LibraryTerm[] {
  const ids = new Set(
    videos
      .filter((v) => (level === "all" || v.levels.includes(level)) && (category === "all" || v.categories.includes(category)))
      .flatMap((v) => v.tags),
  );
  return libraryTags.filter((t) => ids.has(t.id));
}
