export type IconProps = Omit<SVGProps<SVGSVGElement>, "name"> & {
  name: IconName;
  size?: IconSize;
  /** Accessible name; omit for decorative icons. */
  label?: string;
  /** Retired (Trace light point). Accepted for compatibility, ignored. */
  point?: boolean;
};

